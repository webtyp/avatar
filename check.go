//go:build !wasm

package avatar

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
	"webtyp.com/svg/sprite"
)

func Check(prefix, svgFile string) (ids, missing []string, err error) {
	s := sprite.NewSprite()
	b, err := os.ReadFile(svgFile)
	if err != nil {
		return nil, nil, err
	}
	if err := s.AddLayers(prefix, string(b)); err != nil {
		return nil, nil, err
	}

	ids = s.IDs()
	reqs := RequiredSymbols(prefix)

	for _, req := range reqs {
		if !s.Has(req) {
			missing = append(missing, req)
		}
	}

	return ids, missing, nil
}

func GenerateConstants(pkg, prefix string, ids []string) []byte {
	var buf bytes.Buffer
	p := prefix + "-"

	buf.WriteString("// Code generated by avatarc. DO NOT EDIT.\n\n")
	buf.WriteString(fmt.Sprintf("package %s\n\n", pkg))
	buf.WriteString("import \"webtyp.com/svg\"\n\n")
	buf.WriteString(fmt.Sprintf("const Prefix = %q\n\n", prefix))
	buf.WriteString("const (\n")

	type pair struct {
		name, id string
	}
	var pairs []pair

	for _, id := range ids {
		if !strings.HasPrefix(id, p) {
			continue
		}

		suffix := id[len(p):]

		// To CamelCase
		parts := strings.Split(suffix, "-")
		for i, part := range parts {
			if len(part) > 0 {
				parts[i] = strings.ToUpper(part[:1]) + part[1:]
			}
		}
		name := strings.Join(parts, "")

		pairs = append(pairs, pair{name, id})
	}

	sort.Slice(pairs, func(i, j int) bool {
		return pairs[i].name < pairs[j].name
	})

	for _, p := range pairs {
		buf.WriteString(fmt.Sprintf("\t%s svg.Icon = %q\n", p.name, p.id))
	}

	buf.WriteString(")\n")

	res, err := format.Source(buf.Bytes())
	if err != nil {
		return buf.Bytes()
	}

	return res
}
