func TestC3_CheckMinimal(t *testing.T) {
	svg := `<?xml version="1.0" encoding="UTF-8" standalone="no"?><svg viewBox="0 0 512 512" xmlns="http://www.w3.org/2000/svg"><g id="torso-normal"></g><g id="head-normal"></g></svg>`

	tmpfile, err := ioutil.TempFile("", "min.svg")
	if err != nil {
		t.Fatal(err)
	}
	defer os.Remove(tmpfile.Name())

	if _, err := tmpfile.Write([]byte(svg)); err != nil {
		t.Fatal(err)
	}
	if err := tmpfile.Close(); err != nil {
		t.Fatal(err)
	}

	_, missing, err := avatar.Check("t", tmpfile.Name())
	if err != nil {
		t.Fatal(err)
	}

	reqs := avatar.RequiredSymbols("t")
	var expected []string
	for _, r := range reqs {
		if r != "t-torso-normal" && r != "t-head-normal" {
			expected = append(expected, r)
		}
	}

	if len(missing) != len(expected) {
		for i := 0; i < len(missing) || i < len(expected); i++ {
			if i < len(missing) && i < len(expected) && missing[i] != expected[i] {
				t.Errorf("diff at %d: got %s, expected %s", i, missing[i], expected[i])
			} else if i < len(missing) {
				t.Errorf("extra in missing: %s", missing[i])
			} else {
				t.Errorf("extra in expected: %s", expected[i])
			}
		}
		t.Fatalf("lengths differ: got %d, expected %d", len(missing), len(expected))
	}

	for i, m := range missing {
		if i < len(expected) && expected[i] != m {
			t.Errorf("expected %s at %d, got %s", expected[i], i, m)
		}
	}
}

func TestC4_GenerateConstants(t *testing.T) {
	ids := []string{"t-hair-short", "t-talk-a"}
	res := avatar.GenerateConstants("x", "t", ids)

	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "", res, 0)
	if err != nil {
		t.Fatal(err)
	}
	_ = f

	str := string(res)
	if !strings.Contains(str, "HairShort") {
		t.Errorf("missing HairShort")
	}
	if !strings.Contains(str, "TalkA") {
		t.Errorf("missing TalkA")
	}
	if !strings.Contains(str, "const Prefix = \"t\"") {
		t.Errorf("missing Prefix")
	}
	if !strings.Contains(str, "// Code generated by avatarc. DO NOT EDIT.") {
		t.Errorf("missing header")
	}
}

func TestC5_CLI(t *testing.T) {
	dir := t.TempDir()
	bin := filepath.Join(dir, "avatarc")

	cmd := exec.Command("go", "build", "-o", bin, "../cmd/avatarc")
	if err := cmd.Run(); err != nil {
		t.Fatal(err)
	}

	svg := `<?xml version="1.0" encoding="UTF-8" standalone="no"?><svg viewBox="0 0 512 512" xmlns="http://www.w3.org/2000/svg"><g id="torso-normal"></g><g id="head-normal"></g></svg>`
	svgFile := filepath.Join(dir, "min.svg")
	if err := ioutil.WriteFile(svgFile, []byte(svg), 0644); err != nil {
		t.Fatal(err)
	}

	c := exec.Command(bin, "-prefix", "t", "-svg", svgFile, "-pkg", "x", "-out", filepath.Join(dir, "out.go"))
	var stderr bytes.Buffer
	c.Stderr = &stderr

	err := c.Run()
	if err == nil {
		t.Fatal("expected exit 1")
	}

	if c.ProcessState.ExitCode() != 1 {
		t.Errorf("expected exit 1, got %d", c.ProcessState.ExitCode())
	}

	out := stderr.String()
	if !strings.Contains(out, "missing symbol: t-hair-normal") {
		t.Errorf("stderr missing t-hair-normal, got %s", out)
	}

	if _, err := os.Stat(filepath.Join(dir, "out.go")); !os.IsNotExist(err) {
		t.Errorf("expected no out.go")
	}
}

