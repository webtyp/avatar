func TestC1_RequiredSymbols(t *testing.T) {
	reqs := avatar.RequiredSymbols("t")

	// contains t-torso-normal, t-brows-sad, t-mouth-talk-a, t-zzz-3
	wants := []string{"t-torso-normal", "t-brows-sad", "t-mouth-talk-a", "t-zzz-3"}
	for _, w := range wants {
		found := false
		for _, r := range reqs {
			if r == w {
				found = true
				break
			}
		}
		if !found {
			t.Errorf("missing %s", w)
		}
	}

	// no duplicates
	seen := make(map[string]bool)
	for _, r := range reqs {
		if seen[r] {
			t.Errorf("duplicate %s", r)
		}
		seen[r] = true
	}

	// first three are torso, head, hair
	if len(reqs) < 3 || reqs[0] != "t-torso-normal" || reqs[1] != "t-head-normal" || reqs[2] != "t-hair-normal" {
		t.Errorf("first three wrong: %v", reqs[:3])
	}
}

